const ex = (
  name: string,
  group: Exercise["group"],
  equipment: string,
  spec: string[],
  rest: number,
  notes = "",
  unit: Exercise["unit"] = "reps",
): Exercise => ({
  id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
  name,
  group,
  equipment,
  notes,
  unit,
  weeks: spec.map((s, i) => {
    const [sets, reps] = s.split("x");
    return { sets: +sets, reps, rpe: [7, 8, 8, 7][i], rest };
  }),
});
